// Token exporters: one theme → DTCG (per mode), Swift, Kotlin, plain JSON.
// Input is forma-spec.json, so the numbers are exactly what the CSS ships.

const hexToRgb = (hex) => { const n = parseInt(hex.slice(1, 7), 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; };
const camel = (s) => s.replace(/^--/, '').replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const safeIdent = (s) => (/^[0-9]/.test(s) ? `_${s}` : s);

/** Primitive tokens with plain numeric values where they have one (px/rem → points). */
function primitives(spec, theme) {
  const scale = theme?.shape?.radiusScale ?? 1;
  const out = [];
  for (const t of spec.tokens) {
    const name = t.name.replace(/^--/, '');
    let v = String(t.value).trim();
    const scaled = /^calc\(([\d.]+)px \* var\(--radius-scale\)\)$/.exec(v);
    if (scaled) v = `${Math.round(Number(scaled[1]) * scale * 100) / 100}px`;
    if (name === 'border-width-default' && theme?.shape?.borderWidth) v = theme.shape.borderWidth;
    const px = /^(-?[\d.]+)px$/.exec(v), rem = /^(-?[\d.]+)rem$/.exec(v), num = /^-?[\d.]+$/.test(v);
    const points = px ? Number(px[1]) : rem ? Number(rem[1]) * 16 : null;
    out.push({ name, type: t.type, value: v, points, number: num ? Number(v) : null });
  }
  return out;
}

const GROUP = (name) => name.split('-')[0];

/** W3C DTCG (2025.10 color format), one document per mode — the shape Figma variables import and Tokens Studio read. */
export function toDTCG(spec, themeId, mode) {
  const theme = spec.themes.find((t) => t.id === themeId);
  const doc = { $description: `FORMA ${spec.version} · ${theme.name} · ${mode}` };
  const color = (doc.color = {});
  for (const [k, hex] of Object.entries(theme.colors[mode])) {
    const [r, g, b] = hexToRgb(hex);
    const [grp, ...rest] = k.split('-');
    const node = (color[grp] ||= {});
    node[rest.join('-') || 'default'] = { $type: 'color', $value: { colorSpace: 'srgb', components: [r / 255, g / 255, b / 255].map((x) => Math.round(x * 10000) / 10000), alpha: 1, hex } };
  }
  for (const p of primitives(spec, theme)) {
    const grp = GROUP(p.name);
    if (!['space', 'radius', 'text', 'control', 'border', 'duration', 'z', 'container', 'breakpoint', 'weight'].includes(grp)) continue;
    const node = (doc[grp] ||= {});
    const key = p.name.slice(grp.length + 1) || 'default';
    if (p.points != null) node[key] = { $type: 'dimension', $value: { value: p.points, unit: 'px' } };
    else if (grp === 'duration' && /ms$/.test(p.value)) node[key] = { $type: 'duration', $value: { value: Number(p.value.replace('ms', '')), unit: 'ms' } };
    else if (p.number != null) node[key] = { $type: 'number', $value: p.number };
  }
  doc.font = { family: Object.fromEntries(Object.entries(theme.fonts || {}).map(([role, fam]) => [role, { $type: 'fontFamily', $value: fam }])) };
  return doc;
}

export function toSwift(spec, themeId) {
  const theme = spec.themes.find((t) => t.id === themeId);
  const name = `Forma${pascal(theme.id)}`;
  const c = (hex) => { const [r, g, b] = hexToRgb(hex); return `Color(red: ${(r / 255).toFixed(4)}, green: ${(g / 255).toFixed(4)}, blue: ${(b / 255).toFixed(4)})`; };
  const lines = [
    `// Generated by FORMA ${spec.version} — theme "${theme.name}". Do not edit.`,
    'import SwiftUI',
    '',
    `public enum ${name} {`,
    '    /// Colors resolve per appearance: light in light mode, dark in dark mode.',
    '    public enum Colors {',
  ];
  for (const k of Object.keys(theme.colors.light)) {
    lines.push(`        public static let ${safeIdent(camel(k))} = Color(light: ${c(theme.colors.light[k])}, dark: ${c(theme.colors.dark[k])})`);
  }
  lines.push('    }', '');
  for (const grp of ['space', 'radius', 'text', 'control']) {
    const items = primitives(spec, theme).filter((p) => GROUP(p.name) === grp && p.points != null);
    if (!items.length) continue;
    lines.push(`    public enum ${pascal(grp)} {`);
    for (const p of items) lines.push(`        public static let ${safeIdent(camel(p.name.slice(grp.length + 1)))}: CGFloat = ${p.points}`);
    lines.push('    }');
  }
  lines.push('    public enum Fonts {');
  for (const [role, fam] of Object.entries(theme.fonts || {})) lines.push(`        public static let ${role} = "${fam}"`);
  lines.push('    }', '}', '',
    'private extension Color {',
    '    init(light: Color, dark: Color) {',
    '        #if canImport(UIKit)',
    '        self.init(UIColor { $0.userInterfaceStyle == .dark ? UIColor(dark) : UIColor(light) })',
    '        #elseif canImport(AppKit)',
    '        self.init(NSColor(name: nil) { $0.bestMatch(from: [.darkAqua, .aqua]) == .darkAqua ? NSColor(dark) : NSColor(light) })',
    '        #else',
    '        self = light',
    '        #endif',
    '    }',
    '}', '');
  return lines.join('\n');
}

export function toKotlin(spec, themeId, pkg = 'design.forma') {
  const theme = spec.themes.find((t) => t.id === themeId);
  const name = `Forma${pascal(theme.id)}`;
  const c = (hex) => `Color(0xFF${hex.slice(1, 7).toUpperCase()})`;
  const lines = [
    `// Generated by FORMA ${spec.version} — theme "${theme.name}". Do not edit.`,
    `package ${pkg}`,
    '',
    'import androidx.compose.runtime.Composable',
    'import androidx.compose.foundation.isSystemInDarkTheme',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    `object ${name} {`,
    '    class Palette(',
  ];
  const keys = Object.keys(theme.colors.light);
  keys.forEach((k, i) => lines.push(`        val ${safeIdent(camel(k))}: Color${i < keys.length - 1 ? ',' : ''}`));
  lines.push('    )', '');
  for (const mode of ['light', 'dark']) {
    lines.push(`    val ${mode} = Palette(`);
    keys.forEach((k, i) => lines.push(`        ${safeIdent(camel(k))} = ${c(theme.colors[mode][k])}${i < keys.length - 1 ? ',' : ''}`));
    lines.push('    )');
  }
  lines.push('', '    val colors: Palette', '        @Composable get() = if (isSystemInDarkTheme()) dark else light', '');
  for (const grp of ['space', 'radius', 'control']) {
    const items = primitives(spec, theme).filter((p) => GROUP(p.name) === grp && p.points != null);
    if (!items.length) continue;
    lines.push(`    object ${pascal(grp)} {`);
    for (const p of items) lines.push(`        val ${safeIdent(camel(p.name.slice(grp.length + 1)))} = ${p.points}.dp`);
    lines.push('    }');
  }
  const text = primitives(spec, theme).filter((p) => GROUP(p.name) === 'text' && p.points != null);
  if (text.length) { lines.push('    object Text {'); for (const p of text) lines.push(`        val ${safeIdent(camel(p.name.slice(5)))} = ${p.points}.sp`); lines.push('    }'); }
  lines.push('    object Fonts {');
  for (const [role, fam] of Object.entries(theme.fonts || {})) lines.push(`        const val ${role} = "${fam}"`);
  lines.push('    }', '}', '');
  return lines.join('\n');
}

/** Flat JSON for anything else (Style Dictionary input, scripts): { light: {...}, dark: {...}, primitives: {...} }. */
export function toJSON(spec, themeId) {
  const theme = spec.themes.find((t) => t.id === themeId);
  return { name: theme.name, version: spec.version, fonts: theme.fonts, light: theme.colors.light, dark: theme.colors.dark, primitives: Object.fromEntries(spec.tokens.map((t) => [t.name.replace(/^--/, ''), t.value])) };
}

export const FORMATS = ['dtcg', 'swift', 'kotlin', 'json'];

/** → [{ file, content }] */
export function exportTheme(spec, themeId, format) {
  const id = themeId || 'museum';
  if (!spec.themes.some((t) => t.id === id)) throw new Error(`unknown theme "${id}"`);
  if (format === 'dtcg') return ['light', 'dark'].map((m) => ({ file: `${id}.${m}.tokens.json`, content: JSON.stringify(toDTCG(spec, id, m), null, 2) + '\n' }));
  if (format === 'swift') return [{ file: `Forma${pascal(id)}.swift`, content: toSwift(spec, id) }];
  if (format === 'kotlin') return [{ file: `Forma${pascal(id)}.kt`, content: toKotlin(spec, id) }];
  if (format === 'json') return [{ file: `${id}.json`, content: JSON.stringify(toJSON(spec, id), null, 2) + '\n' }];
  throw new Error(`unknown format "${format}" — use ${FORMATS.join(', ')}`);
}
